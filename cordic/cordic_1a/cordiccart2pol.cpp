const data_t pi_div_2 = 1.5707963267948966;

void cordiccart2pol(data_t x, data_t y, data_t * r,  data_t * theta)
{
	#pragma HLS INTERFACE mode=s_axilite port=return
	#pragma HLS INTERFACE mode=s_axilite port=x
	#pragma HLS INTERFACE mode=s_axilite port=y
	#pragma HLS INTERFACE mode=s_axilite port=r
	#pragma HLS INTERFACE mode=s_axilite port=theta
	// Write your code here
    data_t tempX;
	*theta = 0;

    // Quadrant I or II
	if (x < 0) {
		tempX = x;

        // +/- 90 degree rotation
		if (y > 0) {
			x = y;
			y = -tempX;
			*theta += pi_div_2;

		} else {
			x = -y;
			y = tempX;
			*theta -= pi_div_2;
		}
	}

    // Quadrant III or IV
	for(iter_t i_idx = 0; i_idx < NO_ITER; i_idx++) {

		tempX = x;
		if (y > 0) {

			x += y * Kvalues[i_idx];
			y -= tempX * Kvalues[i_idx];

			*theta += angles[i_idx];
            
		} else {
			x -= y * Kvalues[i_idx];
			y += tempX * Kvalues[i_idx];

			*theta -= angles[i_idx];
		}
	}

    // K_values(i) = prod(1 ./ sqrt(1 + 2.^(-2 * i)));
    #if NO_ITER == 10
        *r  = x * 0.6072533210898752864537f;
    #elif NO_ITER == 12
        *r  = x * 0.6072529591389449477035f;
    #elif NO_ITER == 14
        *r  = x * 0.6072529365170102888527f;
    #elif NO_ITER == 16
        *r  = x * 0.6072529351031393796134f;
    #elif NO_ITER == 18
        *r  = x * 0.6072529350147723992137f;
    #elif NO_ITER == 20
        *r  = x * 0.6072529350092494837554f;
    #else
        *r  = x * 0.6072529350088812561694f;
    #endif
}
