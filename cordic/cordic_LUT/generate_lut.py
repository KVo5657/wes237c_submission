
#!/usr/bin/env python3

import math
import sys

W = int(sys.argv[1]) if len(sys.argv) > 1 else 8
# I = 2
I = 3

if W not in (4, 5, 6, 7, 8):
    raise SystemExit("W must be one of: 4, 5, 6, 7, 8")

LUT_SIZE = 1 << (2 * W)
FRAC_BITS = W - I
SCALE = 1 << FRAC_BITS
MASK = (1 << W) - 1


def signed_value(bits):
    """Interpret W bits as a signed two's-complement fixed-point value."""
    if bits & (1 << (W - 1)):
        bits -= 1 << W
    return bits / SCALE


def fixed_bits(value):
    """Quantize to ap_fixed<W,I> with AP_TRN/AP_WRAP behavior."""
    raw = math.floor(value * SCALE)
    return raw & MASK


def generate():
    theta_bits = []
    radius_bits = []

    for index in range(LUT_SIZE):
        x_bits = (index >> W) & MASK
        y_bits = index & MASK

        x = signed_value(x_bits)
        y = signed_value(y_bits)

        if x == 0 and y == 0:
            theta = 0.0
            radius = 0.0
        else:
            theta = math.atan2(y, x)
            radius = math.sqrt(x * x + y * y)

        theta_bits.append(fixed_bits(theta))
        radius_bits.append(fixed_bits(radius))

    with open("cordiccart2pol_lut.h", "w") as f:
        f.write("// Generated by generate_lut.py; do not edit manually.\n")
        f.write(f"// W={W}, I={I}, LUT_SIZE={LUT_SIZE}\n")
        f.write("#ifndef CORDICCART2POL_LUT_H\n")
        f.write("#define CORDICCART2POL_LUT_H\n")
        f.write('#include "cordiccart2pol.h"\n\n')

        f.write(f"static const ap_uint<W> lut_theta_bits[LUT_SIZE] = {{\n")
        for start in range(0, LUT_SIZE, 16):
            f.write("    " + ", ".join(
                str(v) for v in theta_bits[start:start + 16]
            ) + ",\n")
        f.write("};\n\n")

        f.write(f"static const ap_uint<W> lut_radius_bits[LUT_SIZE] = {{\n")
        for start in range(0, LUT_SIZE, 16):
            f.write("    " + ", ".join(
                str(v) for v in radius_bits[start:start + 16]
            ) + ",\n")
        f.write("};\n\n")

        f.write("#endif\n")

    print(f"Generated {LUT_SIZE} entries per table in cordiccart2pol_lut.h")


if __name__ == "__main__":
    generate()
